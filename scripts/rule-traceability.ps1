<#
.SYNOPSIS
    Phase 33 business-rule traceability matrix generated from the code (docs/product/business-rules.md -> code -> tests).

.DESCRIPTION
    For every rule ID in the catalog it lists the production files that cite the rule, the stable problem codes the
    catalog names for it, whether an audit write cites it (`ruleIds:` in an Audit call), and the test methods that cite
    it either as `RULE-NNN` or as `T_RULE_NNN` (backend and frontend suites). A rule is `Traced` when production code
    and at least one test cite it. The matrix is written to the given output path; the script fails when a rule has no
    production citation or no test citation, so a gap cannot pass silently.
#>
[CmdletBinding()]
param(
    [string]$OutputPath,
    [switch]$NoFail
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $OutputPath) { $OutputPath = Join-Path $root 'docs\refactoring\phase-33-traceability.md' }

$catalog = Get-Content -LiteralPath (Join-Path $root 'docs\product\business-rules.md') -Encoding UTF8
$rulePattern = '^\| (?<id>[A-Z]{2,5}-\d{3}) \|(?<text>[^|]*)\|(?<kind>[^|]*)\|'
$rules = foreach ($line in $catalog) {
    if ($line -match $rulePattern) {
        # Capture before the filter below: -match inside Where-Object overwrites $Matches.
        $id = $Matches['id']; $kind = $Matches['kind'].Trim(); $text = $Matches['text'].Trim()
        $codes = [regex]::Matches($line, '`(?<c>[a-z]+(?:[.-][a-z]+)+)`') | ForEach-Object { $_.Groups['c'].Value } |
            Where-Object { $_ -match '^(approval|auth|budget|catalog|concurrency|file|idempotency|organization|purchase-order|quote|receipt|report|requisition|rfq|session|supplier|validation|award|allocation|cost-center|enrichment)[.-]' -and $_ -notmatch '\.(read|manage|create|decide|enter|issue|request|delegate|change|close-early)$' } |
            Sort-Object -Unique
        [pscustomobject]@{ Id = $id; Kind = $kind; Text = $text; Codes = @($codes) }
    }
}

function Get-Sources([string]$Path, [string[]]$Include) {
    Get-ChildItem -Path (Join-Path $root $Path) -Recurse -File -Include $Include |
        Where-Object { $_.FullName -notmatch '[\\/](obj|bin|node_modules|Migrations|generated)[\\/]' }
}

$production = @(Get-Sources 'Src' '*.cs') + @(Get-Sources 'Client\Template.WebApp\src' '*.ts' | Where-Object { $_.Name -notlike '*.spec.ts' })
$tests = @(Get-Sources 'Tests' '*.cs') + @(Get-Sources 'Client\Template.WebApp\e2e' '*.ts') + @(Get-Sources 'Client\Template.WebApp\e2e-real' '*.ts') +
    @(Get-Sources 'Client\Template.WebApp\src' '*.spec.ts')
$productionText = @{}; foreach ($file in $production) { $productionText[$file.FullName] = [IO.File]::ReadAllText($file.FullName) }
$testText = @{}; foreach ($file in $tests) { $testText[$file.FullName] = [IO.File]::ReadAllText($file.FullName) }

function Relative([string]$Path) { $Path.Substring($root.Length + 1).Replace('\', '/') }

$rows = foreach ($rule in $rules) {
    $prefix, $number = $rule.Id -split '-'
    $cite = "(?<![A-Za-z0-9])$prefix[-_]$number(?![0-9])"
    $implemented = @($productionText.Keys | Where-Object { $productionText[$_] -match $cite } | ForEach-Object { Relative $_ } | Sort-Object)
    $audited = @($productionText.Keys | Where-Object { $productionText[$_] -match "ruleIds:[^;]*""$($rule.Id)""" }).Count -gt 0
    $testNames = foreach ($key in $testText.Keys) {
        $text = $testText[$key]
        foreach ($match in [regex]::Matches($text, "(?:public (?:async Task|void) (?<m>\w*$prefix[_]$number\w*)\(|test\('(?<t>[^']*$prefix-$number[^']*)')")) {
            "$(Split-Path -Leaf $key)::$($match.Groups['m'].Value)$($match.Groups['t'].Value)"
        }
        if ($text -match $cite -and -not ([regex]::IsMatch($text, "public (?:async Task|void) \w*$prefix[_]$number"))) {
            "$(Split-Path -Leaf $key) (cited in a test body or comment)"
        }
    }
    $testNames = @($testNames | Sort-Object -Unique)
    [pscustomobject]@{
        Id = $rule.Id; Kind = $rule.Kind; Text = $rule.Text; Codes = $rule.Codes
        Implemented = $implemented; Audited = $audited; Tests = $testNames
        Status = if ($implemented.Count -gt 0 -and $testNames.Count -gt 0) { 'Traced' } else { 'Gap' }
    }
}

$traced = @($rows | Where-Object Status -eq 'Traced').Count
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Phase 33 business-rule traceability matrix')
$lines.Add('')
$lines.Add("Generated by ``scripts/rule-traceability.ps1`` on $(Get-Date -Format 'yyyy-MM-dd') from ``docs/product/business-rules.md``, the production sources (``Src``, ``Client/Template.WebApp/src``) and the test suites. **$traced of $($rows.Count) rules are traced** (cited by production code and by at least one test). ""Audit"" is ``yes`` when an audit write cites the rule in ``ruleIds``; rules enforced as validation, invariants or reads are often audited under the state change that carries them instead. Test names follow ``T_<RULE>_<letter>_...`` (Phase 23 test IDs).")
$lines.Add('')
$lines.Add('| Rule | Kind | API outcome (problem codes) | Audit | Implementation | Tests | Status |')
$lines.Add('|---|---|---|---|---|---|---|')
foreach ($row in $rows) {
    $implementation = if ($row.Implemented.Count -gt 3) { (($row.Implemented | Select-Object -First 3) -join '<br>') + "<br>+$($row.Implemented.Count - 3) more" } else { $row.Implemented -join '<br>' }
    $testCell = if ($row.Tests.Count -gt 3) { (($row.Tests | Select-Object -First 3) -join '<br>') + "<br>+$($row.Tests.Count - 3) more" } else { $row.Tests -join '<br>' }
    $codes = if ($row.Codes.Count -gt 0) { ($row.Codes | ForEach-Object { "``$_``" }) -join ' ' } else { '—' }
    $lines.Add("| $($row.Id) | $($row.Kind) | $codes | $(if ($row.Audited) { 'yes' } else { '—' }) | $implementation | $testCell | $($row.Status) |")
}
[IO.File]::WriteAllLines($OutputPath, $lines, (New-Object Text.UTF8Encoding($false)))

$gaps = @($rows | Where-Object Status -eq 'Gap')
Write-Host "Traceability: $traced/$($rows.Count) rules traced; matrix written to $(Relative $OutputPath)"
foreach ($gap in $gaps) { Write-Host ("GAP {0}: production citations {1}, test citations {2}" -f $gap.Id, $gap.Implemented.Count, $gap.Tests.Count) }
if ($gaps.Count -gt 0 -and -not $NoFail) { exit 1 }
